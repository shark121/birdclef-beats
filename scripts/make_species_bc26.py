"""Write config/species_bc26.json from the BirdCLEF 2026 taxonomy.csv.

Select it with BIRDCLEF_SPECIES_FILE=species_bc26.json. No per-species cap:
the competition's class imbalance is part of the task, so every recording is kept.
"""
import argparse
import csv
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))
from src import config

ap = argparse.ArgumentParser()
ap.add_argument("taxonomy", type=Path, help="path to the competition's taxonomy.csv")
args = ap.parse_args()

with open(args.taxonomy, newline="", encoding="utf-8") as fh:
    rows = list(csv.DictReader(fh))

out = {
    "_comment": "BirdCLEF+ 2026 (Pantanal, Brazil): 234 classes. species_code is the "
                "competition primary_label -- an eBird code for birds, an iNaturalist "
                "taxon id for everything else. Generated by scripts/make_species_bc26.py.",
    "target_recordings_per_species": 100000,
    "species": [{
        "species_code": r["primary_label"],
        "scientific_name": r["scientific_name"],
        "common_name": r["common_name"],
        "taxon_class": r["class_name"],
        "inat_taxon_id": r["inat_taxon_id"],
    } for r in rows],
}
dest = config.CONFIG_DIR / "species_bc26.json"
dest.write_text(json.dumps(out, indent=2, ensure_ascii=False) + "\n", encoding="utf-8")
print(f"wrote {dest}: {len(rows)} classes")
